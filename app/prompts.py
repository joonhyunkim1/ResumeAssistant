def company_block(company: dict | None) -> str:
    if not company:
        return ""
    guide = (company.get("system_prompt") or "").strip()
    if not guide:
        return ""
    return f"\n\n# <기업 맞춤 지침>\n{guide}\n# </기업 맞춤 지침>"


def build_turn_input(message: str, session: dict, company: dict | None, sources: list[dict]) -> str:
    info = []
    if company:
        info.append(f"- 지원 기업: {company['name']}")
        if company.get("position"):
            info.append(f"- 지원 직무: {company['position']}")
    if session.get("question"):
        info.append(f"- 자소서 문항: {session['question']}")
    if session.get("char_limit"):
        lim = int(session["char_limit"])
        info.append(f"- 글자수 제한: {lim}자 (공백 포함, 목표 {int(lim * 0.9)}~{lim}자)")

    if sources:
        refs = "\n\n".join(
            f"[{i}] ({s['category']}) {s['name']}\n{s['text']}" for i, s in enumerate(sources, 1)
        )
    else:
        refs = "(검색된 참고자료 없음 — 사용자 발화에 근거해 작성하고, 필요한 경험은 질문하세요)"

    return (
        f"<작성 정보>\n{chr(10).join(info) or '(미지정)'}\n</작성 정보>\n\n"
        f"<참고자료>\n{refs}\n</참고자료>\n\n"
        f"<요청>\n{message}\n</요청>"
    )
